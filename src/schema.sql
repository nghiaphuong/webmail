CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(64) PRIMARY KEY,
  v MEDIUMTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS admins (
  id INT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  pass_hash VARCHAR(255) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS domains (
  id INT AUTO_INCREMENT PRIMARY KEY,
  domain VARCHAR(190) NOT NULL UNIQUE,
  hostinger_order_id VARCHAR(64) NULL,
  allow_registration TINYINT(1) NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS mailboxes (
  id INT AUTO_INCREMENT PRIMARY KEY,
  address VARCHAR(255) NOT NULL UNIQUE,
  domain_id INT NULL,
  display_name VARCHAR(190) NOT NULL DEFAULT '',
  kind VARCHAR(16) NOT NULL DEFAULT 'admin',
  status VARCHAR(24) NOT NULL DEFAULT 'active',
  provider_id VARCHAR(64) NULL,
  enc_password TEXT NULL,
  note VARCHAR(500) NOT NULL DEFAULT '',
  created_by VARCHAR(64) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login DATETIME NULL,
  INDEX (domain_id), INDEX (kind), INDEX (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS registrations (
  id INT AUTO_INCREMENT PRIMARY KEY,
  local_part VARCHAR(64) NOT NULL,
  domain_id INT NOT NULL,
  display_name VARCHAR(190) NOT NULL DEFAULT '',
  contact_email VARCHAR(255) NOT NULL DEFAULT '',
  reason VARCHAR(1000) NOT NULL DEFAULT '',
  enc_password TEXT NULL,
  lang VARCHAR(5) NOT NULL DEFAULT 'en',
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  reject_reason VARCHAR(500) NOT NULL DEFAULT '',
  status_token CHAR(64) NOT NULL,
  ip VARCHAR(64) NOT NULL DEFAULT '',
  mailbox_id INT NULL,
  decided_by VARCHAR(64) NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  decided_at DATETIME NULL,
  INDEX (status), INDEX (status_token)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS access_links (
  id INT AUTO_INCREMENT PRIMARY KEY,
  mailbox_id INT NOT NULL,
  token_hash CHAR(64) NOT NULL UNIQUE,
  enc_token TEXT NOT NULL,
  can_send TINYINT(1) NOT NULL DEFAULT 1,
  expires_at DATETIME NULL,
  revoked TINYINT(1) NOT NULL DEFAULT 0,
  note VARCHAR(255) NOT NULL DEFAULT '',
  use_count INT NOT NULL DEFAULT 0,
  last_used DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (mailbox_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS sessions (
  id CHAR(64) PRIMARY KEY,
  kind VARCHAR(8) NOT NULL,
  address VARCHAR(255) NULL,
  admin_id INT NULL,
  link_id INT NULL,
  enc_secret TEXT NULL,
  can_send TINYINT(1) NOT NULL DEFAULT 1,
  ip VARCHAR(64) NOT NULL DEFAULT '',
  ua VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at DATETIME NOT NULL,
  INDEX (expires_at), INDEX (address)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS user_prefs (
  address VARCHAR(255) PRIMARY KEY,
  prefs MEDIUMTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS contacts (
  id INT AUTO_INCREMENT PRIMARY KEY,
  owner VARCHAR(255) NOT NULL,
  name VARCHAR(190) NOT NULL DEFAULT '',
  email VARCHAR(255) NOT NULL,
  phone VARCHAR(64) NOT NULL DEFAULT '',
  org VARCHAR(190) NOT NULL DEFAULT '',
  notes VARCHAR(1000) NOT NULL DEFAULT '',
  collected TINYINT(1) NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY owner_email (owner, email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS local_folders (
  id INT AUTO_INCREMENT PRIMARY KEY,
  owner VARCHAR(255) NOT NULL,
  path VARCHAR(255) NOT NULL,
  special VARCHAR(16) NULL,
  UNIQUE KEY owner_path (owner, path)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS local_messages (
  id INT AUTO_INCREMENT PRIMARY KEY,
  owner VARCHAR(255) NOT NULL,
  folder VARCHAR(255) NOT NULL,
  flags VARCHAR(255) NOT NULL DEFAULT '',
  internal_date DATETIME NOT NULL,
  size INT NOT NULL DEFAULT 0,
  subject VARCHAR(500) NOT NULL DEFAULT '',
  from_json TEXT NULL,
  to_json TEXT NULL,
  has_att TINYINT(1) NOT NULL DEFAULT 0,
  search_text MEDIUMTEXT NULL,
  raw LONGBLOB NOT NULL,
  INDEX owner_folder (owner, folder, internal_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS pop3_seen (
  owner VARCHAR(255) NOT NULL,
  uidl VARCHAR(190) NOT NULL,
  seen_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (owner, uidl)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS audit_log (
  id INT AUTO_INCREMENT PRIMARY KEY,
  actor VARCHAR(255) NOT NULL,
  action VARCHAR(64) NOT NULL,
  target VARCHAR(255) NOT NULL DEFAULT '',
  detail VARCHAR(1000) NOT NULL DEFAULT '',
  ip VARCHAR(64) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
